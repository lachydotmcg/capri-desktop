// Builds the Capri Remote test vectors from fixed, obviously fake inputs.
//   node remote/test/make-vectors.mjs           prints vectors.json to stdout
//   node remote/test/make-vectors.mjs --write   rewrites remote/test/vectors.json and the block in remote/PROTOCOL.md
// crypto.test.mjs checks that both files still match what this script computes.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as R from './lib/capri-remote.mjs';

const here = dirname(fileURLToPath(import.meta.url));
export const VECTORS_PATH = join(here, 'vectors.json');
export const PROTOCOL_PATH = join(here, '..', 'PROTOCOL.md');
export const BEGIN = '<!-- vectors:begin (generated by `node remote/test/make-vectors.mjs --write`, do not edit by hand) -->';
export const END = '<!-- vectors:end -->';

const run = (start, length) => Uint8Array.from({ length }, (_, i) => (start + i) & 0xff);

// Sequential bytes: test values only, never real keys.
export const INPUTS = {
  room: run(0x10, 16),
  pcToken: run(0x20, 32),
  code: run(0x40, 16),
  pairingKey: run(0x50, 32),
  pairNonce: run(0x70, 16),
  deviceId: run(0x80, 16),
  deviceToken: run(0x90, 32),
  deviceKey: run(0xb0, 32),
  phoneNonce: run(0xd0, 16),
  pcNonce: run(0xe0, 16),
};

const keysHex = (keys) => ({
  phoneToPc: { enc: R.hex(keys.phoneToPc.enc), mac: R.hex(keys.phoneToPc.mac) },
  pcToPhone: { enc: R.hex(keys.pcToPhone.enc), mac: R.hex(keys.pcToPhone.mac) },
});

export async function buildVectors() {
  const I = INPUTS;
  const b = Object.fromEntries(Object.entries(I).map(([name, bytes]) => [name, R.b64u(bytes)]));

  const rfcIkm = new Uint8Array(22).fill(0x0b);
  const rfcSalt = run(0x00, 13);
  const rfcInfo = run(0xf0, 10);
  const rfc = await R.hkdf(rfcIkm, rfcSalt, rfcInfo, 42);

  const pairOkm = await R.hkdf(I.pairingKey, I.pairNonce, R.LABELS.pair, 128);
  const helloOkm = await R.hkdf(I.deviceKey, I.deviceId, R.LABELS.hello, 128);
  const sessionOkm = await R.hkdf(I.deviceKey, R.concat(I.phoneNonce, I.pcNonce), R.LABELS.session, 128);
  const confirmBytes = await R.hkdf(I.pairingKey, I.pairNonce, R.LABELS.confirm, 4);
  const pair = R.splitKeys(pairOkm);
  const hello = R.splitKeys(helloOkm);
  const session = R.splitKeys(sessionOkm);
  const sets = { pair, hello, session };

  const reply = `Hi Lachy, caf${String.fromCodePoint(0xe9)} ${String.fromCodePoint(0x2615)} ${String.fromCodePoint(0x1f431)}`;
  const specs = [
    { name: 'pair-request', keys: 'pair.phoneToPc', kind: 1, dir: 1, seq: 0, iv: run(0x00, 16),
      message: { type: 'pair-request', v: 1, name: 'Test Phone', app: 'remote-web/test' } },
    { name: 'pair-allow', keys: 'pair.pcToPhone', kind: 1, dir: 2, seq: 0, iv: run(0x10, 16),
      message: { type: 'pair-allow', v: 1, device: b.deviceId, token: b.deviceToken, key: b.deviceKey, name: 'Test PC', app: 'capri/test' } },
    { name: 'pair-deny', keys: 'pair.pcToPhone', kind: 1, dir: 2, seq: 0, iv: run(0x20, 16),
      message: { type: 'pair-deny', v: 1, reason: 'denied' } },
    { name: 'hello', keys: 'hello.phoneToPc', kind: 2, dir: 1, seq: 0, iv: run(0x30, 16),
      message: { type: 'hello', v: 1, nonce: b.phoneNonce, name: 'Test Phone', app: 'remote-web/test' } },
    { name: 'hello-ok', keys: 'hello.pcToPhone', kind: 2, dir: 2, seq: 0, iv: run(0x40, 16),
      message: { type: 'hello-ok', v: 1, nonce: b.pcNonce, echo: b.phoneNonce, name: 'Test PC', app: 'capri/test', features: ['chat'] } },
    { name: 'chat.send', keys: 'session.phoneToPc', kind: 3, dir: 1, seq: 0, iv: run(0x50, 16),
      message: { type: 'chat.send', id: 'm1', text: 'Hello, Capri!' } },
    { name: 'chat.send with picture', keys: 'session.phoneToPc', kind: 3, dir: 1, seq: 1, iv: run(0x80, 16),
      message: { type: 'chat.send', id: 'm2', text: '', picture: { mime: 'image/png', data: 'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR4nGP4____fwAJ-wP9KobjigAAAABJRU5ErkJggg' } } },
    { name: 'chat.typing (32-byte plaintext, so a whole block of padding)', keys: 'session.pcToPhone', kind: 3, dir: 2, seq: 0, iv: run(0x60, 16),
      message: { type: 'chat.typing', on: true } },
    { name: 'chat.reply (seq 0x01020304, non-ASCII text)', keys: 'session.pcToPhone', kind: 3, dir: 2, seq: 0x01020304, iv: run(0x70, 16),
      message: { type: 'chat.reply', id: 'r1', re: 'm1', text: reply, done: true } },
  ];

  const envelopes = [];
  for (const spec of specs) {
    const [set, way] = spec.keys.split('.');
    const plaintext = R.encodeMessage(spec.message);
    const envelope = await R.seal(sets[set][way], spec.kind, spec.dir, spec.seq, plaintext, spec.iv);
    envelopes.push({
      name: spec.name, keys: spec.keys, kind: spec.kind, dir: spec.dir, seq: spec.seq, iv: R.hex(spec.iv),
      plaintext: JSON.stringify(spec.message), plaintextHex: R.hex(plaintext), envelope: R.hex(envelope),
    });
  }

  const chatSend = R.fromHex(envelopes.find((e) => e.name === 'chat.send').envelope);
  const flip = (index, bit = 1) => { const copy = chatSend.slice(); copy[index] ^= bit; return R.hex(copy); };
  const rejects = [
    { name: 'one bit flipped in the ciphertext', envelope: flip(24), keys: 'session.phoneToPc', kind: 3, dir: 1, seq: 0, reason: 'mac' },
    { name: 'one bit flipped in the sequence number', envelope: flip(7), keys: 'session.phoneToPc', kind: 3, dir: 1, seq: 0, reason: 'mac' },
    { name: 'one bit flipped in the tag', envelope: flip(chatSend.length - 1), keys: 'session.phoneToPc', kind: 3, dir: 1, seq: 0, reason: 'mac' },
    { name: 'last byte cut off', envelope: R.hex(chatSend.subarray(0, chatSend.length - 1)), keys: 'session.phoneToPc', kind: 3, dir: 1, seq: 0, reason: 'length' },
    { name: 'replayed: the valid chat.send when seq 1 is expected', envelope: R.hex(chatSend), keys: 'session.phoneToPc', kind: 3, dir: 1, seq: 1, reason: 'seq' },
    { name: 'valid chat.send opened as a hello', envelope: R.hex(chatSend), keys: 'session.phoneToPc', kind: 2, dir: 1, seq: 0, reason: 'context' },
    { name: 'valid chat.send opened with the PC->phone keys', envelope: R.hex(chatSend), keys: 'session.pcToPhone', kind: 3, dir: 1, seq: 0, reason: 'mac' },
  ];

  const pairRequest = R.fromHex(envelopes.find((e) => e.name === 'pair-request').envelope);
  const pairAllow = R.fromHex(envelopes.find((e) => e.name === 'pair-allow').envelope);
  const typing = R.fromHex(envelopes.find((e) => e.name.startsWith('chat.typing')).envelope);
  const pendingId = run(0xa0, 16);

  return {
    protocol: R.PROTOCOL,
    note: 'Test values only. Byte strings are lowercase hex unless the field ends in B64u. Plaintexts are the exact UTF-8 bytes in plaintextHex.',
    labels: R.LABELS,
    inputs: Object.fromEntries(Object.entries(I).map(([name, bytes]) => [name, { hex: R.hex(bytes), b64u: R.b64u(bytes) }])),
    qrUrl: R.qrUrl(b.room, b.code, b.pairingKey),
    hashes: {
      codeHashB64u: await R.hashB64u(I.code),
      pcTokenHashB64u: await R.hashB64u(I.pcToken),
      deviceTokenHashB64u: await R.hashB64u(I.deviceToken),
    },
    hkdfRfc5869Case1: { ikm: R.hex(rfcIkm), salt: R.hex(rfcSalt), info: R.hex(rfcInfo), length: 42, okm: R.hex(rfc) },
    confirm: { okm: R.hex(confirmBytes), code: await R.confirmCode(I.pairingKey, I.pairNonce) },
    pairKeys: { salt: R.hex(I.pairNonce), okm: R.hex(pairOkm), ...keysHex(pair) },
    helloKeys: { salt: R.hex(I.deviceId), okm: R.hex(helloOkm), ...keysHex(hello) },
    sessionKeys: { salt: R.hex(R.concat(I.phoneNonce, I.pcNonce)), okm: R.hex(sessionOkm), ...keysHex(session) },
    envelopes,
    rejects,
    frames: {
      relayToPcChatSend: R.hex(R.pcFrame(I.deviceId, chatSend)),
      pcToRelayChatTyping: R.hex(R.pcFrame(I.deviceId, typing)),
    },
    controls: {
      pcAuth: JSON.stringify({ t: 'auth', token: b.pcToken }),
      pcCode: JSON.stringify({ t: 'code', hash: await R.hashB64u(I.code), ttl: 600 }),
      phonePair: JSON.stringify({ t: 'pair', code: b.code, nonce: b.pairNonce, env: R.b64u(pairRequest) }),
      relayPending: JSON.stringify({ t: 'pending', id: R.b64u(pendingId), nonce: b.pairNonce, env: R.b64u(pairRequest) }),
      pcAdmit: JSON.stringify({ t: 'admit', pending: R.b64u(pendingId), device: b.deviceId, tokenHash: await R.hashB64u(I.deviceToken), env: R.b64u(pairAllow) }),
      phoneAuth: JSON.stringify({ t: 'auth', device: b.deviceId, token: b.deviceToken }),
    },
  };
}

export function renderMarkdown(v) {
  const lines = [];
  const block = (title, rows) => {
    lines.push(`**${title}**`, '', '```text', ...rows, '```', '');
  };
  block('Inputs (hex, then base64url)', Object.entries(v.inputs).map(([name, value]) => `${name.padEnd(12)} ${value.hex}  ${value.b64u}`));
  block('QR URL and relay hashes', [
    `qrUrl               ${v.qrUrl}`,
    `SHA-256(code)       ${v.hashes.codeHashB64u}   (the "hash" in the code control)`,
    `SHA-256(pcToken)    ${v.hashes.pcTokenHashB64u}`,
    `SHA-256(devToken)   ${v.hashes.deviceTokenHashB64u}   (the "tokenHash" in admit)`,
  ]);
  const h = v.hkdfRfc5869Case1;
  block('HKDF-SHA256, RFC 5869 test case 1 (checks a hand-rolled HKDF)', [`ikm  ${h.ikm}`, `salt ${h.salt}`, `info ${h.info}`, `L    ${h.length}`, `okm  ${h.okm}`]);
  block('Confirmation code: HKDF(ikm=pairingKey, salt=pairNonce, info="capri-remote/1 confirm", L=4)', [`okm  ${v.confirm.okm}`, `code ${v.confirm.code}`]);
  for (const [title, keys] of [
    ['Pairing keys: HKDF(ikm=pairingKey, salt=pairNonce, info="capri-remote/1 pair", L=128)', v.pairKeys],
    ['Hello keys: HKDF(ikm=deviceKey, salt=deviceId, info="capri-remote/1 hello", L=128)', v.helloKeys],
    ['Session keys: HKDF(ikm=deviceKey, salt=phoneNonce||pcNonce, info="capri-remote/1 session", L=128)', v.sessionKeys],
  ]) {
    block(title, [
      `salt           ${keys.salt}`,
      `okm            ${keys.okm}`,
      `phoneToPc.enc  ${keys.phoneToPc.enc}`,
      `phoneToPc.mac  ${keys.phoneToPc.mac}`,
      `pcToPhone.enc  ${keys.pcToPhone.enc}`,
      `pcToPhone.mac  ${keys.pcToPhone.mac}`,
    ]);
  }
  for (const e of v.envelopes) {
    block(`Envelope: ${e.name}`, [
      `keys      ${e.keys}   kind ${e.kind}   dir ${e.dir}   seq ${e.seq}`,
      `iv        ${e.iv}`,
      `plaintext ${e.plaintextHex}`,
      `envelope  ${e.envelope}`,
    ]);
  }
  block('Must be rejected (every one of these fails to open)', v.rejects.map((r) => `${r.reason.padEnd(8)} ${r.name}: open with ${r.keys}, kind ${r.kind}, dir ${r.dir}, seq ${r.seq}\n         ${r.envelope}`));
  block('Binary frames between the PC and the relay (16-byte device id, then the envelope)', [
    `relay->PC chat.send    ${v.frames.relayToPcChatSend}`,
    `PC->relay chat.typing  ${v.frames.pcToRelayChatTyping}`,
  ]);
  block('Text frames built from the same values', Object.entries(v.controls).map(([name, text]) => `${name.padEnd(13)} ${text}`));
  lines.push('The plaintext of each envelope, as text, is in `remote/test/vectors.json` (`envelopes[].plaintext`).');
  return lines.join('\n');
}

export function spliceProtocol(doc, markdown) {
  const start = doc.indexOf(BEGIN);
  const end = doc.indexOf(END);
  if (start < 0 || end < start) throw new Error('PROTOCOL.md is missing the vectors markers');
  return doc.slice(0, start + BEGIN.length) + '\n\n' + markdown + '\n\n' + doc.slice(end);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const vectors = await buildVectors();
  const json = JSON.stringify(vectors, null, 2) + '\n';
  if (process.argv.includes('--write')) {
    writeFileSync(VECTORS_PATH, json);
    writeFileSync(PROTOCOL_PATH, spliceProtocol(readFileSync(PROTOCOL_PATH, 'utf8'), renderMarkdown(vectors)));
    console.log('Wrote ' + VECTORS_PATH + ' and the vectors block in ' + PROTOCOL_PATH);
  } else {
    process.stdout.write(json);
  }
}
